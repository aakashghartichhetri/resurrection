-- Upgrade an MVP 1 database without dropping events or checkpoints.
CREATE TABLE workflow_commands (
    id UUID PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    action VARCHAR(40) NOT NULL,
    step INTEGER NOT NULL CHECK (step BETWEEN 0 AND 3),
    status VARCHAR(20) NOT NULL,
    resulting_sequence BIGINT NOT NULL,
    fail_next_step BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_workflow_commands_workflow ON workflow_commands(workflow_id);

CREATE TABLE recovery_approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    actor VARCHAR(100) NOT NULL,
    action VARCHAR(40) NOT NULL,
    approved_sequence BIGINT NOT NULL,
    history_hash VARCHAR(100) NOT NULL,
    before_step INTEGER NOT NULL,
    before_status VARCHAR(20) NOT NULL,
    after_step INTEGER NOT NULL,
    after_status VARCHAR(20) NOT NULL,
    approved_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_recovery_approvals_workflow ON recovery_approvals(workflow_id, approved_at);

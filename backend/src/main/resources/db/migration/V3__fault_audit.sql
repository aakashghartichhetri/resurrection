-- A separate audit records deliberate corruption without making it part of the trusted event history.
CREATE TABLE fault_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    actor VARCHAR(100) NOT NULL,
    type VARCHAR(40) NOT NULL,
    before_step INTEGER NOT NULL,
    before_status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_fault_audits_workflow ON fault_audits(workflow_id, created_at);

CREATE TABLE workflows (
    id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    step INTEGER NOT NULL CHECK (step BETWEEN 0 AND 3),
    last_sequence BIGINT NOT NULL DEFAULT 0,
    fail_next_step BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE workflow_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    sequence_number BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    message VARCHAR(500) NOT NULL,
    previous_hash VARCHAR(100) NOT NULL,
    hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT unique_workflow_event_sequence UNIQUE (workflow_id, sequence_number)
);

CREATE TABLE workflow_checkpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id UUID NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    sequence_number BIGINT NOT NULL,
    step INTEGER NOT NULL CHECK (step BETWEEN 0 AND 3),
    status VARCHAR(20) NOT NULL,
    last_event_hash VARCHAR(100) NOT NULL,
    checksum VARCHAR(100) NOT NULL,
    CONSTRAINT unique_workflow_checkpoint_sequence UNIQUE (workflow_id, sequence_number)
);

CREATE INDEX idx_events_workflow ON workflow_events(workflow_id, sequence_number);
CREATE INDEX idx_checkpoints_workflow ON workflow_checkpoints(workflow_id, sequence_number);
